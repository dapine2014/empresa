package com.aicompany.core.agent.validation;

import com.aicompany.core.agent.model.DevelopmentResult.GeneratedFile;
import org.junit.jupiter.api.Test;

import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** Spec Diego ambientes §3: error con sentencia y línea; el SQL válido de PostgreSQL nunca bloquea. */
class MigrationSqlCheckTest {

    private static List<String> check(String sql) {
        return MigrationSqlCheck.errors(List.of(new GeneratedFile(MigrationFilesGate.ROOT + "V1__x.sql", sql)));
    }

    private static void assertValid(String sql) {
        assertEquals(List.of(), check(sql), sql);
    }

    @Test
    void parenthesisWithoutClosingReportsStatementAndLine() {
        var errors = check("""
                CREATE TABLE a (id int);
                -- comentario
                CREATE TABLE clientes (id uuid PRIMARY KEY, nombre text NOT NULL;
                """);
        assertEquals(1, errors.size(), errors.toString());
        assertTrue(errors.get(0).startsWith("db/postgres/migrations/V1__x.sql, sentencia 2 (línea 3): "), errors.get(0));
        assertTrue(errors.get(0).endsWith("Corrige el SQL de PostgreSQL."), errors.get(0));
    }

    @Test
    void validSupportedStatementsPass() {
        assertValid("""
                CREATE TABLE IF NOT EXISTS clientes (
                  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
                  nombre text NOT NULL,
                  edad integer CHECK (edad >= 0),
                  creado timestamptz NOT NULL DEFAULT now(),
                  CONSTRAINT uq UNIQUE (nombre)
                );
                CREATE UNIQUE INDEX ux_clientes_nombre ON clientes (nombre);
                CREATE INDEX ix_activos ON clientes (nombre) WHERE edad > 18;
                ALTER TABLE clientes ADD CONSTRAINT ck CHECK (edad < 150);
                ALTER TABLE clientes ADD COLUMN IF NOT EXISTS email text;
                INSERT INTO clientes (nombre, edad) VALUES ('a;b', 3);
                UPDATE clientes SET edad = 4 WHERE nombre = 'x';
                DELETE FROM clientes WHERE edad IS NULL;
                DROP TABLE IF EXISTS viejo;
                DROP INDEX IF EXISTS ix_viejo;
                """);
    }

    @Test
    void postgresConstructsThatTheParserMayNotKnowNeverBlock() {
        assertValid("CREATE TABLE t (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, n text);");
        assertValid("CREATE TABLE t (id bigint GENERATED BY DEFAULT AS IDENTITY, n text[] NOT NULL DEFAULT '{}');");
        assertValid("CREATE TABLE t (id int PRIMARY KEY, c_id int REFERENCES c(id) ON DELETE CASCADE);");
        assertValid("CREATE TABLE t (a int, b int GENERATED ALWAYS AS (a * 2) STORED);");
        assertValid("CREATE TABLE t (id int, j jsonb NOT NULL DEFAULT '{}'::jsonb);");
        assertValid("INSERT INTO t (id) VALUES (1) ON CONFLICT (id) DO NOTHING;");
        assertValid("INSERT INTO t (id, n) VALUES (1, 'a') ON CONFLICT (id) DO UPDATE SET n = EXCLUDED.n RETURNING id;");
        assertValid("CREATE INDEX CONCURRENTLY ix ON t USING gin (j);");
        assertValid("CREATE INDEX ix ON t (lower(n)) INCLUDE (id);");
        assertValid("ALTER TABLE t ENABLE ROW LEVEL SECURITY;");
        assertValid("ALTER TABLE t ALTER COLUMN n TYPE varchar(20) USING n::varchar;");
        assertValid("ALTER TABLE t ADD CONSTRAINT fk FOREIGN KEY (c_id) REFERENCES c (id) ON DELETE SET NULL;");
        assertValid("UPDATE t SET n = x.n FROM x WHERE x.id = t.id RETURNING t.id;");
        assertValid("DELETE FROM t USING x WHERE x.id = t.id;");
        assertValid("DROP TABLE a, b CASCADE;");
        assertValid("DROP FUNCTION IF EXISTS f(int);");
        assertValid("CREATE TABLE t (id int) PARTITION BY RANGE (id);");
        assertValid("CREATE UNLOGGED TABLE t (id int) WITH (fillfactor = 70);");
        assertValid("CREATE TABLE t2 (LIKE t INCLUDING ALL);");
        assertValid("CREATE TABLE t3 AS SELECT 1 AS x;");
        assertValid("CREATE INDEX ix ON t USING btree (a DESC NULLS LAST, b);");
        assertValid("ALTER TABLE t RENAME COLUMN a TO b;");
        assertValid("ALTER TABLE t RENAME TO t9;");
        assertValid("ALTER TABLE ONLY t ALTER COLUMN a SET DEFAULT now() + interval '1 day';");
        assertValid("ALTER TABLE t ALTER COLUMN a SET NOT NULL, DROP COLUMN IF EXISTS z;");
        assertValid("ALTER TABLE t ADD COLUMN x int GENERATED ALWAYS AS IDENTITY;");
        assertValid("CREATE TABLE t (a int, b varchar(10)[], EXCLUDE USING gist (a WITH =));");
        assertValid("INSERT INTO t (a) SELECT a FROM u WHERE a > 1;");
        assertValid("UPDATE t SET (a, b) = (1, 2) WHERE c = 'e;x';");
        assertValid("WITH x AS (SELECT 1) INSERT INTO t SELECT * FROM x;");
        assertValid("INSERT INTO t (a) VALUES (E'it\\'s; ok');");
        assertValid("CREATE TABLE t (a numeric(10,2) DEFAULT 0 NOT NULL, b timestamp without time zone, c double precision);");
        assertValid("ALTER TABLE t ADD CONSTRAINT fk FOREIGN KEY (a) REFERENCES b(id) NOT VALID;");
        assertValid("ALTER TABLE t ALTER COLUMN a SET DATA TYPE bigint;");
        assertValid("ALTER TABLE t ADD CONSTRAINT x EXCLUDE USING gist (a WITH &&);");
        assertValid("UPDATE ONLY t SET a = 1;");
        assertValid("DELETE FROM ONLY t WHERE a = 1;");
        assertValid("DROP INDEX CONCURRENTLY IF EXISTS ix;");
        assertValid("ALTER TABLE t ADD CONSTRAINT c CHECK (a > 0) NO INHERIT;");
        assertValid("CREATE UNIQUE INDEX CONCURRENTLY IF NOT EXISTS ix ON t (a, b DESC);");
        assertValid("CREATE TEMP TABLE t (a int) ON COMMIT DROP;");
    }

    @Test
    void structuralErrorsAreCaughtInEveryStatementKind() {
        var alter = check("ALTER TABLE t\n  ADD CONSTRAINT c CHECK (a > 0;");
        assertEquals(1, alter.size(), alter.toString());
        assertTrue(alter.get(0).contains("sentencia 1") && alter.get(0).contains("'(' sin cerrar (abre en la línea 2)"),
                alter.get(0));
        var update = check("SELECT 1;\nUPDATE t SET n = 'abc WHERE a = 1;\n");
        assertEquals(1, update.size(), update.toString());
        assertTrue(update.get(0).contains("comillas simples sin cerrar (abre en la línea 2)"), update.get(0));
        var extra = check("DELETE FROM t WHERE (a = 1));");
        assertTrue(extra.get(0).contains("')' sobrante en la línea 1"), extra.toString());
        assertTrue(check("CREATE FUNCTION f() RETURNS int AS $$ SELECT 1;").get(0).contains("sin cerrar"));
        assertValid("DO $$ BEGIN PERFORM (1; END $$;");
        assertValid("-- ( comentario con ' y (\nUPDATE t SET n = ')' WHERE (a = 1);");
    }

    @Test
    void parserMessageIsReducedToTokenAndPosition() {
        var errors = check("CREATE TABLE a (id int);\n\nCREATE TABLE c (id int,, n text);");
        assertEquals(1, errors.size(), errors.toString());
        assertTrue(errors.get(0).contains("Encountered \",\" en la línea 3, columna "), errors.get(0));
        assertTrue(!errors.get(0).contains("expansion") && !errors.get(0).contains("lexical"), errors.get(0));
    }

    @Test
    void unsupportedStatementsPassUnparsed() {
        assertValid("""
                CREATE EXTENSION IF NOT EXISTS pgcrypto;
                CREATE FUNCTION f() RETURNS trigger AS $$
                BEGIN
                  UPDATE x SET a = 1; RETURN NEW;
                END
                $$ LANGUAGE plpgsql;
                DO $body$ BEGIN PERFORM 1; END $body$;
                COMMENT ON TABLE t IS 'a;b';
                CREATE TYPE estado AS ENUM ('a', 'b');
                CREATE VIEW v AS SELECT 1;
                GRANT SELECT ON t TO PUBLIC;
                """);
    }

    @Test
    void semicolonsInsideQuotesAndCommentsDoNotSplit() {
        assertValid("""
                -- un; comentario
                /* otro; /* anidado; */ comentario; */
                INSERT INTO t (n) VALUES ('uno; dos');
                INSERT INTO t (n) VALUES ('it''s; ok');
                INSERT INTO "t;x" (n) VALUES ($q$a;b$q$);
                """);
    }

    @Test
    void errorIsReportedEvenAfterDollarBlock() {
        var errors = check("""
                DO $$ BEGIN PERFORM 1; END $$;
                INSERT INTO t (a, b VALUES (1, 2);
                """);
        assertEquals(1, errors.size(), errors.toString());
        assertTrue(errors.get(0).contains("sentencia 2 (línea 2)"), errors.get(0));
    }

    @Test
    void filesOutsideTheMigrationsFolderAreIgnored() {
        var errors = MigrationSqlCheck.errors(List.of(
                new GeneratedFile("backend/seed.sql", "CREATE TABLE ("),
                new GeneratedFile(MigrationFilesGate.ROOT + "V2__ok.sql", "CREATE TABLE a (id int);")));
        assertEquals(List.of(), errors);
    }
}
